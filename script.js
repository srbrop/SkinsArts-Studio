async function handleSearchBaseSkin() {
    const usernameInput = document.getElementById('username-input');
    const fetchBtn = document.getElementById('fetch-api-btn');
    if (!usernameInput || !usernameInput.value.trim()) return;

    const rawInput = usernameInput.value.trim();
    const names = rawInput.split(',').map(s => s.trim()).filter(Boolean);

    if (skinApiStatus) {
        skinApiStatus.textContent = dict[currentLang]['mojang_searching'];
        skinApiStatus.className = 'status-note';
    }
    if (fetchBtn) fetchBtn.disabled = true;

    if (names.length === 1) {
        try {
            const { dataUrl, isSlim, resolvedName } = await fetchOfficialMinecraftSkin(names[0]);
            const slot = getActiveSlot();
            slot.name = resolvedName;
            slot.isSlim = isSlim;
            slot.preset = 'btn-custom';
            slot.img.src = dataUrl;
            setActiveBaseButton('btn-custom');
            const modelTag = isSlim ? 'Alex 3px' : 'Steve 4px';
            if (skinApiStatus) {
                skinApiStatus.textContent = `${slot.label}: ${resolvedName} (${modelTag})`;
                skinApiStatus.className = 'status-note success';
            }
        } catch (err) {
            if (skinApiStatus) {
                skinApiStatus.textContent = dict[currentLang]['mojang_error'];
                skinApiStatus.className = 'status-note error';
            }
        } finally {
            if (fetchBtn) fetchBtn.disabled = false;
        }
    } else {
        const targetCount = Math.min(names.length, 3);
        const results = [];
        let successCount = 0;

        for (let i = 0; i < targetCount; i++) {
            try {
                const res = await fetchOfficialMinecraftSkin(names[i]);
                skinSlots[i].name = res.resolvedName;
                skinSlots[i].isSlim = res.isSlim;
                skinSlots[i].preset = 'btn-custom';
                skinSlots[i].img.src = res.dataUrl;
                results.push(`${skinSlots[i].id}:${res.resolvedName}`);
                successCount++;
            } catch (err) {
                results.push(`${skinSlots[i].id}:Error`);
            }
        }

        if (skinDistributionMode === 'single') {
            setDistributionMode('cycle');
        }

        if (skinApiStatus) {
            if (successCount > 0) {
                skinApiStatus.textContent = `${dict[currentLang]['mojang_found']} ${results.join(' | ')}`;
                skinApiStatus.className = 'status-note success';
            } else {
                skinApiStatus.textContent = dict[currentLang]['mojang_error'];
                skinApiStatus.className = 'status-note error';
            }
        }
        if (fetchBtn) fetchBtn.disabled = false;
        updateActiveSlotUI();
        renderMosaicEnVivo();
    }
}

