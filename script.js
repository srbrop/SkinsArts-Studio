function getSlotForTile(x, y) {
    if (skinDistributionMode === 'cycle') {
        const uploadIndex = (2 - y) * 9 + (8 - x);
        const slotIdx = uploadIndex % 3;
        return skinSlots[slotIdx] || skinSlots[0];
    } else if (skinDistributionMode === 'rows') {
        return skinSlots[y] || skinSlots[0];
    } else {
        return getActiveSlot();
    }
}

function updateSlotMiniCanvas(idx) {
    const slot = skinSlots[idx];
    if (!slot || !slot.img.complete || slot.img.naturalWidth === 0) return;
    const miniC = document.getElementById(`slot-canvas-${idx}`);
    if (miniC) {
        const mCtx = miniC.getContext('2d');
        mCtx.imageSmoothingEnabled = false;
        mCtx.clearRect(0, 0, 8, 8);
        mCtx.drawImage(slot.img, 8, 8, 8, 8, 0, 0, 8, 8);
        mCtx.drawImage(slot.img, 40, 8, 8, 8, 0, 0, 8, 8);
    }
    const subEl = document.getElementById(`slot-sub-${idx}`);
    if (subEl) {
        subEl.textContent = slot.name;
    }
}

