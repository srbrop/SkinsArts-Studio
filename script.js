function sinc(x) {
    if (x === 0) return 1;
    const px = Math.PI * x;
    return Math.sin(px) / px;
}

function lanczos3(x) {
    const ax = Math.abs(x);
    if (ax >= 3) return 0;
    return sinc(ax) * sinc(ax / 3);
}

function buildLanczosWeights(srcSize, dstSize, a = 3) {
    const scale = dstSize / srcSize;
    const filterRadius = a / scale;
    const weightsTable = [];

    for (let dst = 0; dst < dstSize; dst++) {
        const center = (dst + 0.5) / scale - 0.5;
        const start = Math.max(0, Math.floor(center - filterRadius));
        const end = Math.min(srcSize - 1, Math.ceil(center + filterRadius));
        let totalW = 0;
        const taps = [];
        for (let src = start; src <= end; src++) {
            const w = lanczos3((src - center) * scale);
            taps.push({ src, w });
            totalW += w;
        }
        const invW = totalW !== 0 ? 1 / totalW : 0;
        for (let k = 0; k < taps.length; k++) {
            taps[k].w *= invW;
        }
        weightsTable.push(taps);
    }
    return weightsTable;
}

function fastLanczos3Resample(srcData, srcW, srcH, dstW, dstH) {
    const hWeights = buildLanczosWeights(srcW, dstW, 3);
    const vWeights = buildLanczosWeights(srcH, dstH, 3);

    const tmp = new Float32Array(dstW * srcH * 4);
    for (let y = 0; y < srcH; y++) {
        const ySrcOff = y * srcW * 4;
        const yTmpOff = y * dstW * 4;
        for (let x = 0; x < dstW; x++) {
            const taps = hWeights[x];
            let r = 0, g = 0, b = 0, a = 0;
            for (let i = 0; i < taps.length; i++) {
                const tap = taps[i];
                const sIdx = ySrcOff + tap.src * 4;
                const w = tap.w;
                r += srcData[sIdx] * w;
                g += srcData[sIdx + 1] * w;
                b += srcData[sIdx + 2] * w;
                a += srcData[sIdx + 3] * w;
            }
            const dIdx = yTmpOff + x * 4;
            tmp[dIdx] = r;
            tmp[dIdx + 1] = g;
            tmp[dIdx + 2] = b;
            tmp[dIdx + 3] = a;
        }
    }

    const out = new Uint8ClampedArray(dstW * dstH * 4);
    for (let y = 0; y < dstH; y++) {
        const taps = vWeights[y];
        const yOutOff = y * dstW * 4;
        for (let x = 0; x < dstW; x++) {
            let r = 0, g = 0, b = 0, a = 0;
            for (let j = 0; j < taps.length; j++) {
                const tap = taps[j];
                const tIdx = (tap.src * dstW + x) * 4;
                const w = tap.w;
                r += tmp[tIdx] * w;
                g += tmp[tIdx + 1] * w;
                b += tmp[tIdx + 2] * w;
                a += tmp[tIdx + 3] * w;
            }
            const outIdx = yOutOff + x * 4;
            out[outIdx] = Math.max(0, Math.min(255, Math.round(r)));
            out[outIdx + 1] = Math.max(0, Math.min(255, Math.round(g)));
            out[outIdx + 2] = Math.max(0, Math.min(255, Math.round(b)));
            out[outIdx + 3] = Math.max(0, Math.min(255, Math.round(a)));
        }
    }
    return out;
}

