botonGenerar?.addEventListener('click', async () => {
    const prefijos = ['a', 'b', 'c'];
    const hashesInBatch = new Set();
    const zip = new JSZip();

    for (let y = 0; y < 3; y++) {
        for (let x = 0; x < 9; x++) {
            const finalCanvas = buildSingleSkinCanvas(x, y);
            const finalCtx = finalCanvas.getContext('2d');

            let base64DataRaw = finalCanvas.toDataURL("image/png").split(',')[1];
            let tweakX = 0;
            while (hashesInBatch.has(base64DataRaw) && tweakX < 64) {
                const px = 8 + (tweakX % 8);
                const py = 8 + Math.floor(tweakX / 8);
                const imgData = finalCtx.getImageData(px, py, 1, 1);
                imgData.data[0] = imgData.data[0] === 255 ? 254 : imgData.data[0] + 1;
                if (imgData.data[3] === 0) imgData.data[3] = 1;
                finalCtx.putImageData(imgData, px, py);
                base64DataRaw = finalCanvas.toDataURL("image/png").split(',')[1];
                tweakX++;
            }
            hashesInBatch.add(base64DataRaw);
            zip.file(`${prefijos[y]}(${x + 1}).png`, base64DataRaw, { base64: true });
        }
    }

    if (canvas) {
        const artBase64 = canvas.toDataURL("image/png").split(',')[1];
        zip.file("Art_Mural_72x24.png", artBase64, { base64: true });
    }
    zip.file("README.txt", dict[currentLang]['readme']);

    const contenido = await zip.generateAsync({ type: "blob" });
    const url = URL.createObjectURL(contenido);
    const link = document.createElement("a");
    link.href = url;
    link.download = "SkinsArt_generated.zip";
    link.click();
    setTimeout(() => URL.revokeObjectURL(url), 5000);
});

