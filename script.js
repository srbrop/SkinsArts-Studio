function detectSkinModelIsSlim(img) {
    const tempC = document.createElement('canvas');
    tempC.width = 64;
    tempC.height = 64;
    const tCx = tempC.getContext('2d');
    tCx.drawImage(img, 0, 0, 64, 64);
    const data = tCx.getImageData(0, 0, 64, 64).data;

    const alphaAt = (x, y) => data[(y * 64 + x) * 4 + 3];

    let outerStripOpaque = 0;
    for (let y = 20; y < 32; y++) {
        if (alphaAt(54, y) > 0 || alphaAt(55, y) > 0) outerStripOpaque++;
    }
    for (let y = 16; y < 20; y++) {
        if (alphaAt(50, y) > 0 || alphaAt(51, y) > 0) outerStripOpaque++;
    }

    let innerArmOpaque = 0;
    for (let y = 20; y < 32; y++) {
        if (alphaAt(44, y) > 0 || alphaAt(45, y) > 0) innerArmOpaque++;
    }

    return innerArmOpaque > 0 && outerStripOpaque === 0;
}

function mirrorImage(context, imageCanvas, x, y, horizontal, vertical) {
    context.save();
    context.setTransform(
        horizontal ? -1 : 1, 0,
        0, vertical ? -1 : 1,
        x + (horizontal ? imageCanvas.width : 0),
        y + (vertical ? imageCanvas.height : 0)
    );
    context.drawImage(imageCanvas, 0, 0);
    context.restore();
}

function processBlock(srcCanvas, srow, scol, w, h, drow, dcol, dCanvas, fliph = false, flipv = false) {
    const cCanvas = document.createElement('canvas');
    cCanvas.width = w;
    cCanvas.height = h;
    const cCtx = cCanvas.getContext("2d");
    cCtx.drawImage(srcCanvas, scol, srow, w, h, 0, 0, w, h);
    const aCanvas = document.createElement('canvas');
    aCanvas.width = w;
    aCanvas.height = h;
    const aCtx = aCanvas.getContext("2d");
    mirrorImage(aCtx, cCanvas, 0, 0, fliph, flipv);
    dCanvas.getContext("2d").drawImage(aCanvas, 0, 0, w, h, dcol, drow, w, h);
}

